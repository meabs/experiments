"""Writes SDD's trial files (Linux, bubblewrap, hosted gpt-5.6-luna at medium effort). See README.md for the design.
One trial file per arm. Tickets, setup.sh, verify.sh and the hidden tests are ELC's, read from 2026-11-evidence-led.

- V: Shopizer as it is.                      - D: ELC's disciplined setup (its arms/D, unchanged).
- L: D's six lines plus long reference notes (arms/L).
- R: research, plan, implement, by prompt (arms/R/suffix.md).
- S: Spec Kit bug-fixing skills (arms/S, build with scripts/make_arms.sh) + arms/S/suffix.md.
- O: OpenSpec skills (arms/O) + arms/O/suffix.md; the openspec command comes from build/openspec.

Every arm's prompt is HEAD + the ELC ticket (+ the arm's suffix, if any). Usage:
  python3 -I make_trial.py [--pilot V,D] [--tasks T1,T2] [--reps N]
"""
import glob
import os
import sys
import tomllib

E = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ELC = os.path.join(os.path.dirname(E), "2026-11-evidence-led")
U = os.path.expanduser("~")
S = f"{U}/code/benchmark/local-setup"
JDK = "/usr/lib/jvm/java-21-openjdk-amd64"
HEAD = ("You are working in a checkout of shopizer, a Java e-commerce platform "
        "(Maven, several modules; JDK 21 is installed and JAVA_HOME is set).\n\n")
EFFORT = "medium"
REPS = 5
TIMEOUT = 3600
ARMS = ("V", "D", "L", "R", "S", "O")
OVERLAY = {"V": None, "D": f"{ELC}/arms/D", "L": f"{E}/arms/L", "R": None, "S": f"{E}/arms/S", "O": f"{E}/arms/O"}
OSPEC = f"{E}/build/openspec"
USES = {"S": "speckit-bug", "O": "openspec"}  # a run "used the toolkit" if a tool call matches


def suffix(arm):
    p = f"{E}/arms/{arm}/suffix.md"
    return open(p).read().rstrip("\n") if os.path.exists(p) else ""


def agent(arm):
    script = f"{E}/build/codex-bwrap-sdd.sh" if arm == "O" else f"{S}/codex-bwrap.sh"
    cmd = ["bash", script, "exec", "-s", "danger-full-access", "--skip-git-repo-check", "--json",
           "--model", "gpt-5.6-luna", "-c", f'model_reasoning_effort="{EFFORT}"', "{prompt}"]
    env = f'JAVA_HOME = "{JDK}", PATH = "{JDK}/bin:/usr/local/bin:/usr/bin:/bin", CODEX_PROFILE = "hosted"'
    if arm == "O":
        env += f', CODEX_RO_BIND = "{OSPEC}", CODEX_EXTRA_PATH = "{OSPEC}/node_modules/.bin"'
    return ('[[agents]]\nname = "codex"\n'
            '# hosted gpt-5.6-luna (CODEX_PROFILE=hosted); codex runs inside bubblewrap\n'
            'model = "gpt-5.6-luna"\ncommand = [' + ", ".join('"' + c.replace('"', '\\"') + '"' for c in cmd) + ']\n'
            f'args = []\nedits = true\nsandbox = "danger-full-access"\nenv = {{ {env} }}\nisolate = []\n\n')


def trial(name, arm, tasks, reps):
    arm_t = f'[[arms]]\nname = "{arm}"\n'
    if OVERLAY[arm]:
        arm_t += f'overlay = "{OVERLAY[arm]}"\n'
    if arm in USES:
        arm_t += f'uses = "{USES[arm]}"\n'
    s = (f"# Generated by 2026-11-spec-driven/scripts/make_trial.py. Arm {arm}, effort {EFFORT}.\n"
         f'name = "{name}"\n\n[defaults]\nreps = {reps}\nparallel = 3\ntimeout = {TIMEOUT}\nbaseline = "{arm}"\nclaim = true\n\n'
         f'[[repos]]\nname = "shopizer"\nsource = "{U}/code/benchmark/skills-impact-work/shopizer"\nref = "6a4a0a6"\n\n'
         + arm_t + f'setup = ["bash {ELC}/scripts/setup.sh"]\nparallel_setup = true\n\n' + agent(arm))
    for t in tasks:
        p = HEAD + open(os.path.join(ELC, "tasks", t, "prompt.md")).read().strip()
        assert '"""' not in p and p.endswith("saying what you changed.")
        p += suffix(arm)
        s += f'[[questions]]\nid = "{t}"\nrepo = "shopizer"\nverify = "bash {ELC}/scripts/verify.sh"\nprompt = """{p}"""\n\n'
    return s


def arg(flag, default=None):
    return sys.argv[sys.argv.index(flag) + 1] if flag in sys.argv else default


if __name__ == "__main__":
    tasks = sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(ELC, "tasks", "*", "prompt.md"))
                   if not os.path.exists(os.path.join(os.path.dirname(p), "PILOT-ONLY")))
    if arg("--tasks"):
        tasks = arg("--tasks").split(",")
    reps = int(arg("--reps", REPS))
    arms, prefix = (arg("--pilot").split(","), "trial-pilot") if arg("--pilot") else (ARMS, "trial")
    for a in arms:
        text = trial(f"sdd-{prefix[6:] or 'main'}-{a}", a, tasks, reps)
        t = tomllib.loads(text)
        cmd = t["agents"][0]["command"]
        assert f'model_reasoning_effort="{EFFORT}"' in cmd and "gpt-5.6-luna" in cmd
        assert ("overlay" in t["arms"][0]) == (OVERLAY[a] is not None)
        assert all(os.path.isdir(OVERLAY[a]) for _ in [0] if OVERLAY[a])
        assert ("CODEX_EXTRA_PATH" in t["agents"][0]["env"]) == (a == "O")
        f = f"{prefix}-{a}.local.toml"
        open(os.path.join(E, f), "w").write(text)
        print(f, a, len(t["questions"]), "tasks, reps", t["defaults"]["reps"])
