"""Writes ELC's trial files (Linux, bubblewrap via local-setup/codex-bwrap.sh, hosted gpt-5.6-luna at medium effort).
See README.md for the design. One trial file per arm, because an arm's Codex settings differ:

- V (vanilla): Shopizer as it is, Codex defaults.
- D (disciplined): arms/D copied into the clone (AGENTS.md and .agents/skills/), Codex defaults.
- E (evidence-led): arms/E/repo copied into the clone (AGENTS.md); a Codex home seeded from arms/E/codex-home (the
  user-level AGENTS.md, hooks.json and the gate); subagents off (--disable multi_agent); hooks trusted.

Every arm gets the same prompt: HEAD + the ticket (tasks/<T>/prompt.md, which ends with the reply instruction).

Usage: python3 -I make_trial.py [--pilot V] [--tasks T1,T2] [--reps N]
"""
import glob
import os
import sys
import tomllib

E = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
U = os.path.expanduser("~")
S = f"{U}/code/benchmark/local-setup"
JDK = "/usr/lib/jvm/java-21-openjdk-amd64"
HEAD = ("You are working in a checkout of shopizer, a Java e-commerce platform "
        "(Maven, several modules; JDK 21 is installed and JAVA_HOME is set).\n\n")
EFFORT = "medium"
REPS = 5
TIMEOUT = 3600
ARMS = ("V", "D", "E")
SEED = f"{E}/build/E-codex-home"  # arms/E/codex-home with hooks.json written for this machine's home (gitignored)


def write_seed():
    import shutil
    if os.path.exists(SEED):
        shutil.rmtree(SEED)
    shutil.copytree(f"{E}/arms/E/codex-home", SEED)
    t = f"{SEED}/.codex/hooks.json.template"
    open(f"{SEED}/.codex/hooks.json", "w").write(open(t).read().replace("@HOME@", U))
    os.remove(t)


def agent(arm):
    cmd = ["bash", f"{S}/codex-bwrap.sh", "exec", "-s", "danger-full-access", "--skip-git-repo-check", "--json"]
    if arm == "E":
        cmd += ["--disable", "multi_agent", "--dangerously-bypass-hook-trust"]
    cmd += ["--model", "gpt-5.6-luna", "-c", f'model_reasoning_effort="{EFFORT}"', "{prompt}"]
    env = f'JAVA_HOME = "{JDK}", PATH = "{JDK}/bin:/usr/local/bin:/usr/bin:/bin", CODEX_PROFILE = "hosted"'
    if arm == "E":
        env += f', CODEX_SEED = "{SEED}"'
    return ('[[agents]]\nname = "codex"\n'
            '# hosted gpt-5.6-luna (CODEX_PROFILE=hosted); codex runs inside bubblewrap (codex-bwrap.sh)\n'
            'model = "gpt-5.6-luna"\ncommand = [' + ", ".join('"' + c.replace('"', '\\"') + '"' for c in cmd) + ']\n'
            f'args = []\nedits = true\nsandbox = "danger-full-access"\nenv = {{ {env} }}\nisolate = []\n\n')


def trial(name, arm, tasks, reps):
    overlay = {"V": None, "D": f"{E}/arms/D", "E": f"{E}/arms/E/repo"}[arm]
    s = (f"# Generated by 2026-11-evidence-led/scripts/make_trial.py. Arm {arm}, effort {EFFORT}.\n"
         f'name = "{name}"\n\n[defaults]\nreps = {reps}\nparallel = 3\ntimeout = {TIMEOUT}\nbaseline = "{arm}"\nclaim = true\n\n'
         f'[[repos]]\nname = "shopizer"\nsource = "{U}/code/benchmark/skills-impact-work/shopizer"\nref = "6a4a0a6"\n\n'
         f'[[arms]]\nname = "{arm}"\n' + (f'overlay = "{overlay}"\n' if overlay else "") +
         f'setup = ["bash {E}/scripts/setup.sh"]\nparallel_setup = true\n\n' + agent(arm))
    for t in tasks:
        p = HEAD + open(os.path.join(E, "tasks", t, "prompt.md")).read().strip()
        assert '"""' not in p and p.endswith("saying what you changed.")
        s += f'[[questions]]\nid = "{t}"\nrepo = "shopizer"\nverify = "bash {E}/scripts/verify.sh"\nprompt = """{p}"""\n\n'
    return s


def arg(flag, default=None):
    return sys.argv[sys.argv.index(flag) + 1] if flag in sys.argv else default


if __name__ == "__main__":
    # tickets retired by the pilot rule keep a PILOT-ONLY marker and are never in a main trial
    tasks = sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(E, "tasks", "*", "prompt.md"))
                   if not os.path.exists(os.path.join(os.path.dirname(p), "PILOT-ONLY")))
    if arg("--tasks"):
        tasks = arg("--tasks").split(",")
    reps = int(arg("--reps", REPS))
    if arg("--pilot"):
        arms, prefix = arg("--pilot").split(","), "trial-pilot"
    else:
        arms, prefix = ARMS, "trial"
    if "E" in arms:
        write_seed()
    for a in arms:
        text = trial(f"elc-{prefix[6:] or 'main'}-{a}", a, tasks, reps)
        t = tomllib.loads(text)
        cmd = t["agents"][0]["command"]
        assert f'model_reasoning_effort="{EFFORT}"' in cmd
        assert ("--disable" in cmd) == (a == "E") and ("CODEX_SEED" in t["agents"][0]["env"]) == (a == "E")
        assert ("overlay" in t["arms"][0]) == (a != "V")
        f = f"{prefix}-{a}.local.toml"
        open(os.path.join(E, f), "w").write(text)
        print(f, a, len(t["questions"]), "tasks, reps", t["defaults"]["reps"])
