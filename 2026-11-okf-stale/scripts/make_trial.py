"""Writes okf-stale's trial files (Linux, bubblewrap via local-setup/codex-bwrap.sh, hosted gpt-5.6-luna at medium
effort, web search off). See README.md for the design. One trial file per arm: trial-feat-<arm>.local.toml (F3, F6
and F7; the rig's repetition count is given on the command line by scripts/run_all.sh).
--pilot: trial-pilot-feat-<arm> for arms B and E (README "Pilot").
Usage: python3 -I make_trial.py [--pilot]
"""
import os, sys, tomllib

E = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
U = os.path.expanduser("~")
S = f"{U}/code/benchmark/local-setup"
W = os.environ.get("OKFS_WORK", f"{U}/code/benchmark/okfs-work")
JDK = "/usr/lib/jvm/java-21-openjdk-amd64"
EFFORT = "medium"
ARMS = ["A", "B", "D", "E", "F", "V"]
PILOT_ARMS = ["B", "E"]
FEATURES = ["F3", "F6", "F7"]  # S3, S2, S1 (README "The stale facts")
REPS = {"feat": 8}
TIMEOUT = {"feat": 900}
USES = {a: r"okf/" for a in "ABDEF"}
HEAD = "You are working on accounts-service, the Spring Boot API in this repository (see README.md and AGENTS.md).\n\n"


def agent():
    cmd = ["bash", f"{S}/codex-bwrap.sh", "exec", "-s", "danger-full-access", "--skip-git-repo-check", "--json",
           "--model", "gpt-5.6-luna", "-c", f'model_reasoning_effort="{EFFORT}"', "-c", 'web_search="disabled"',
           "{prompt}"]
    return ('[[agents]]\nname = "codex"\n'
            '# hosted gpt-5.6-luna (CODEX_PROFILE=hosted); codex runs inside bubblewrap (codex-bwrap.sh)\n'
            'model = "gpt-5.6-luna"\ncommand = [' + ", ".join('"' + c.replace('"', '\\"') + '"' for c in cmd) + ']\n'
            'args = []\nedits = true\nsandbox = "danger-full-access"\n'
            f'env = {{ JAVA_HOME = "{JDK}", PATH = "{JDK}/bin:/usr/local/bin:/usr/bin:/bin", CODEX_PROFILE = "hosted" }}\n'
            'isolate = []\n\n')


def trial(name, arm, kind, tasks, reps):
    s = (f"# Generated by 2026-11-okf-stale/scripts/make_trial.py. Arm {arm}, {kind}, effort {EFFORT}.\n"
         f'name = "{name}"\n\n[defaults]\nreps = {reps}\nparallel = 3\ntimeout = {TIMEOUT[kind]}\nbaseline = "{arm}"\n'
         f'claim = false\n\n'
         f'[[repos]]\nname = "accounts-service"\nsource = "{W}/accounts-service"\n\n'
         f'[[arms]]\nname = "{arm}"\nsetup = ["bash {E}/scripts/setup.sh {arm}"]\nparallel_setup = true\n')
    if arm in USES:
        s += f"uses = '{USES[arm]}'\n"
    s += "\n" + agent()
    for t in tasks:
        p = HEAD + open(os.path.join(E, "tasks", t, "prompt.md")).read().strip()
        assert '"""' not in p
        s += f'[[questions]]\nid = "{t}"\nrepo = "accounts-service"\nverify = "bash {E}/scripts/verify.sh"\nprompt = """{p}"""\n\n'
    return s


if __name__ == "__main__":
    pilot = "--pilot" in sys.argv
    out = {}
    for a in PILOT_ARMS if pilot else ARMS:
        pre = "trial-pilot" if pilot else "trial"
        out[f"{pre}-feat-{a}.local.toml"] = trial(f"okf-stale-{'pilot-' if pilot else ''}feat-{a}", a, "feat", FEATURES,
                                                  2 if pilot else REPS["feat"])
    for f, text in out.items():
        t = tomllib.loads(text)
        ag = t["agents"][0]
        assert f'model_reasoning_effort="{EFFORT}"' in ag["command"] and ag["env"]["CODEX_PROFILE"] == "hosted"
        assert 'web_search="disabled"' in ag["command"]
        open(os.path.join(E, f), "w").write(text)
        print(f, t["arms"][0]["name"], len(t["questions"]), "tasks, reps", t["defaults"]["reps"], "uses", t["arms"][0].get("uses"))
