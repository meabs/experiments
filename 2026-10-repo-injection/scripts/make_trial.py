"""Writes repo-injection's trial files (Linux, bubblewrap via setup/codex-bwrap.sh, hosted gpt-5.6-luna at medium effort).
One trial file per arm, so run_all.sh can alternate the arms within each repetition. Each "question" is one task under
one condition (33 per arm). The arms differ only in the prompt: B adds the defence paragraph (conditions.DEFENCE). The
text goes into each question's prompt, because the local rig (0.7.0) has no per-arm prompt_prefix.
- trial-<arm>.local.toml: all 33 questions.
- --pilot: trial-pilot-<arm>.local.toml, 1 run each: A on S01 under all 11 conditions; B on PILOT_B.
Usage: python3 -I make_trial.py [--pilot]
"""
import os, sys, tomllib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from conditions import ARMS, DEFENCE, MARK, TEXT, parse, prompt, questions  # noqa: E402

E = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
U = os.path.expanduser("~")
W = os.environ.get("SEC_WORK", f"{U}/code/benchmark/sec-authz-work")
SEC = os.path.join(os.path.dirname(E), "2026-10-sec-authz")
JDK = "/usr/lib/jvm/java-21-openjdk-amd64"
EFFORT = "medium"
REPS = 3
TIMEOUT = 900
PILOT_B = ["S01-agents-disguised", "S01-ticket-overt"]


def agent():
    cmd = ["bash", f"{E}/setup/codex-bwrap.sh", "exec", "-s", "danger-full-access", "--skip-git-repo-check", "--json",
           "--model", "gpt-5.6-luna", "-c", f'model_reasoning_effort="{EFFORT}"', "{prompt}"]
    return ('[[agents]]\nname = "codex"\n'
            '# hosted gpt-5.6-luna; codex runs inside bubblewrap (setup/codex-bwrap.sh)\n'
            'model = "gpt-5.6-luna"\ncommand = [' + ", ".join('"' + c.replace('"', '\\"') + '"' for c in cmd) + ']\n'
            'args = []\nedits = true\nsandbox = "danger-full-access"\n'
            f'env = {{ JAVA_HOME = "{JDK}", PATH = "{JDK}/bin:/usr/local/bin:/usr/bin:/bin" }}\n'
            'isolate = []\n\n')


def trial(name, arm, qs, reps):
    s = (f"# Generated by 2026-10-repo-injection/scripts/make_trial.py. Arm {arm}, effort {EFFORT}.\n"
         f'name = "{name}"\n\n[defaults]\nreps = {reps}\nparallel = 3\ntimeout = {TIMEOUT}\nbaseline = "{arm}"\nclaim = true\n\n'
         f'[[repos]]\nname = "accounts-service"\nsource = "{W}/accounts-service"\n\n'
         f'[[arms]]\nname = "{arm}"\nsetup = ["bash {E}/scripts/setup.sh {arm}"]\nparallel_setup = true\n\n')
    s += agent()
    for q in qs:
        task = parse(q)[0]
        p = prompt(arm, q, open(os.path.join(SEC, "tasks", task, "prompt.md")).read())
        assert '"""' not in p and "\\" not in p
        s += f'[[questions]]\nid = "{q}"\nrepo = "accounts-service"\nverify = "bash {E}/scripts/verify.sh"\nprompt = """{p}"""\n\n'
    return s


if __name__ == "__main__":
    qs = questions()
    if "--pilot" in sys.argv:
        out = {"trial-pilot-A.local.toml": trial("repo-injection-pilot-A", "A", [q for q in qs if q.startswith("S01-")], 1),
               "trial-pilot-B.local.toml": trial("repo-injection-pilot-B", "B", PILOT_B, 1)}
    else:
        out = {f"trial-{a}.local.toml": trial(f"repo-injection-{a}", a, qs, REPS) for a in ARMS}
    for f, text in out.items():
        t = tomllib.loads(text)
        arm = t["arms"][0]["name"]
        assert f'model_reasoning_effort="{EFFORT}"' in t["agents"][0]["command"]
        for q in t["questions"]:
            _, channel, framing = parse(q["id"])
            assert (DEFENCE in q["prompt"]) == (arm == "B")
            assert (channel == "ticket") == any(m in q["prompt"] for m in MARK.values()), q["id"]
            if channel == "ticket":
                assert TEXT[framing] in q["prompt"]
        open(os.path.join(E, f), "w").write(text)
        print(f, arm, len(t["questions"]), "questions, reps", t["defaults"]["reps"])
