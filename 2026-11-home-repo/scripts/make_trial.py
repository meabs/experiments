"""Writes HR-1's trial files, one per arm (A..F): hosted gpt-5.6-luna via local-setup/codex-bwrap.sh (CODEX_PROFILE=hosted),
medium effort, web search off, OKF test G's four task prompts (okf-local/scripts/make_trial.py), plus for the Home Repo arms a
first sentence saying where the task is. Usage: python3 -I make_trial.py [--pilot]   (pilot: task g1 only, 1 rep)"""
import os, pathlib, sys

E = pathlib.Path(__file__).resolve().parent.parent
HOME = pathlib.Path.home()
WORK = pathlib.Path(os.environ.get("HR_WORK", HOME / "code/benchmark/hr-work"))
OKFL = E.parent / "2026-10-okf-local"
SETUP = HOME / "code/benchmark/local-setup"
src = (OKFL / "scripts/make_trial.py").read_text()
ns = {}
exec(src[src.index("T = {"):src.index("TIMEOUT =")], ns)
T = ns["T"]
PILOT = "--pilot" in sys.argv
if PILOT:
    T = {k: v for k, v in T.items() if k.startswith("g1")}
if not PILOT:
    T = {k: v for k, v in T.items() if not k.startswith("g1")}  # amendment 2: g1 is answerable without the backend
REPS = 1 if PILOT else 4
HOMEPRE = ("You are in our Home Repo. The task is in the storefront repository; AGENTS.md says where our repositories "
           "are.\n\n")
for arm in "ABCDEF":
    ro = f', CODEX_RO_BIND = "{WORK / "remotes"}"' if arm == "C" else ""
    qs = "\n".join(
        f'[[questions]]\nid = "{k}"\nrepo = "hr"\nverify = "bash {E}/scripts/verify.sh {k}"\n'
        f'prompt = """{("" if arm == "A" else HOMEPRE) + v}"""\n' for k, v in T.items())
    toml = f'''# HR-1 arm {arm}. Generated by scripts/make_trial.py.
name = "home-repo-{arm}{"-pilot" if PILOT else ""}"

[defaults]
reps = {REPS}
parallel = 3
timeout = 900
baseline = "{arm}"
prompt_suffix = "Say briefly which files you used."

[[repos]]
name = "hr"
source = "{WORK / "arms" / arm}"

[[arms]]
name = "{arm}"

[[agents]]
name = "codex"
model = "gpt-5.6-luna"
command = ["bash", "{E}/setup/codex-bwrap.sh", "exec", "-s", "danger-full-access", "--skip-git-repo-check", "--json", "--model", "gpt-5.6-luna", "-c", "model_reasoning_effort=\\"medium\\"", "-c", "web_search=\\"disabled\\"", "{{prompt}}"]
args = []
edits = true
sandbox = "danger-full-access"
env = {{ OKF_EXP = "{OKFL}", CODEX_PROFILE = "hosted"{ro} }}

{qs}'''
    (E / f"trial-{'pilot-' if PILOT else ''}{arm}.local.toml").write_text(toml)
    print(arm, len(T), "tasks, reps", REPS)
