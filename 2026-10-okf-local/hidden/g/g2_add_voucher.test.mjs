import assert from "node:assert/strict";
import { pathToFileURL } from "node:url";
const { ax, dispatch, noToast, load } = await import(pathToFileURL(process.env.OKF_EXP + "/hidden/g/_prelude.mjs"));
const { addToCart } = await load("src/redux/actions/cartActions.js");
const item = { id: 7, sku: "ABC-1" };
ax.calls.length = 0; ax.replies.push({ code: "C1" });
await addToCart(item, noToast, undefined, 2, "DEFAULT", null, undefined, "SAVE10")(dispatch);
let c = ax.calls.find((x) => x.method === "POST");
assert.equal(c.url, "cart/?store=DEFAULT"); assert.equal(c.data.product, "ABC-1"); assert.equal(c.data.quantity, 2);
assert.equal(c.data.voucher, "SAVE10", "the discount code goes in the field the backend's cart-item request defines");
ax.calls.length = 0; ax.replies.push({ code: "C1" });
await addToCart(item, noToast, "C1", 1, "DEFAULT", null, [{ id: 3 }], "SAVE10")(dispatch);
c = ax.calls.find((x) => x.method === "PUT");
assert.equal(c.url, "cart/C1?store=DEFAULT"); assert.deepEqual(c.data.attributes, [{ id: 3 }]); assert.equal(c.data.voucher, "SAVE10");
ax.calls.length = 0; ax.replies.push({ code: "C1" });
await addToCart(item, noToast, undefined, 1, "DEFAULT", null, undefined)(dispatch);
c = ax.calls.find((x) => x.method === "POST");
assert.ok(!("voucher" in c.data) || c.data.voucher === undefined, "no discount field when none is given");
console.log("ok");
