"""Writes arm A's trial file: one Codex agent (0.157.0, gpt-5.6-luna, medium effort) in ELC's bubblewrap rig.

Arm A is ELC's vanilla arm V with two changes, both made so that A matches B and C:
- no claim line (claim = false): Machinist's arms get the ticket only, so A does too;
- the ticket text is built by ticket_text() below, which B and C use as well (run_bc.py).
Everything else is ELC's: the single-commit checkout of 6a4a0a6 (ELC's setup.sh), the hosted login copy with an
empty config, the sandbox (local-setup/codex-bwrap.sh), the 3600 s timeout and ELC's verify.sh.

Usage: python3 -I make_trial_a.py (--pilot | --main) [--tasks T1,T2] [--reps N]
"""
import os
import sys
import tomllib

X = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ELC = os.path.join(os.path.dirname(X), "2026-11-evidence-led")
U = os.path.expanduser("~")
S = f"{U}/code/benchmark/local-setup"
JDK = "/usr/lib/jvm/java-21-openjdk-amd64"
HEAD = ("You are working in a checkout of shopizer, a Java e-commerce platform "
        "(Maven, several modules; JDK 21 is installed and JAVA_HOME is set).\n\n")
TASKS = ("CATEGORYDELETE", "CUSTOMERCART", "PRODUCTDELETE", "REVIEWS", "STOCK", "SUPPORTORDERS",  # hard
         "RETURNS", "VISIBILITY")                                                                # easy
EFFORT = "medium"
TIMEOUT = 3600


def ticket_text(t):
    """The exact text every arm is given for ticket t: ELC's header line and the ticket (ending with its reply line)."""
    p = HEAD + open(os.path.join(ELC, "tasks", t, "prompt.md")).read().strip()
    assert '"""' not in p and p.endswith("saying what you changed."), t
    return p


def trial(name, tasks, reps):
    cmd = ["bash", f"{S}/codex-bwrap.sh", "exec", "-s", "danger-full-access", "--skip-git-repo-check", "--json",
           "--model", "gpt-5.6-luna", "-c", f'model_reasoning_effort="{EFFORT}"', "{prompt}"]
    s = (f"# Generated by 2026-11-asf-1/scripts/make_trial_a.py. Arm A, effort {EFFORT}.\n"
         f'name = "{name}"\n\n[defaults]\nreps = {reps}\nparallel = 1\ntimeout = {TIMEOUT}\nbaseline = "A"\nclaim = false\n\n'
         f'[[repos]]\nname = "shopizer"\nsource = "{U}/code/benchmark/skills-impact-work/shopizer"\nref = "6a4a0a6"\n\n'
         f'[[arms]]\nname = "A"\nsetup = ["bash {ELC}/scripts/setup.sh"]\nparallel_setup = true\n\n'
         '[[agents]]\nname = "codex"\n'
         '# hosted gpt-5.6-luna (CODEX_PROFILE=hosted); codex runs inside bubblewrap (codex-bwrap.sh)\n'
         'model = "gpt-5.6-luna"\ncommand = [' + ", ".join('"' + c.replace('"', '\\"') + '"' for c in cmd) + ']\n'
         'args = []\nedits = true\nsandbox = "danger-full-access"\n'
         f'env = {{ JAVA_HOME = "{JDK}", PATH = "{JDK}/bin:/usr/local/bin:/usr/bin:/bin", CODEX_PROFILE = "hosted" }}\n'
         'isolate = []\n\n')
    for t in tasks:
        s += (f'[[questions]]\nid = "{t}"\nrepo = "shopizer"\nverify = "bash {ELC}/scripts/verify.sh"\n'
              f'prompt = """{ticket_text(t)}"""\n\n')
    return s


def arg(flag, default=None):
    return sys.argv[sys.argv.index(flag) + 1] if flag in sys.argv else default


if __name__ == "__main__":
    kind = "pilot" if "--pilot" in sys.argv else "main" if "--main" in sys.argv else sys.exit(__doc__)
    tasks = arg("--tasks").split(",") if arg("--tasks") else list(TASKS)
    reps = int(arg("--reps", 1 if kind == "pilot" else 4))
    text = trial(f"asf-{kind}-A", tasks, reps)
    t = tomllib.loads(text)
    assert t["defaults"]["claim"] is False and len(t["questions"]) == len(tasks)
    assert 'model_reasoning_effort="medium"' in t["agents"][0]["command"]
    f = os.path.join(X, f"trial-{kind}-A.local.toml")
    open(f, "w").write(text)
    print(os.path.basename(f), len(tasks), "tasks, reps", reps)
