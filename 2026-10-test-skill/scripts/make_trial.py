"""Writes the three trial files for test-skill. Codex, 3 runs per task, 20 tasks. See README.md for the design.

- trial.toml, low effort: none (task only); instruction (prompt starts with arms/instruction.md); skill (arms/instruction-skill.md,
  and the original verify-api skill in the clone); skill-revised (the same, with the revised skill).
- trial-medium.toml: arm medium, task only, at medium effort (the rig cannot set effort per arm).
- trial-gate.toml: arm gate, task only, low effort, with the Stop-hook gate. Its agent uses home-gate (scripts/make_gate_home.sh),
  whose hooks.json runs gate.sh; --dangerously-bypass-hook-trust lets that hook run without an interactive trust review.

Usage: python3 -I make_trial.py. Paths use the /Users/USER placeholder; run scripts/localize.sh after.
"""
import glob, os

E = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
U = "/Users/USER"
X = f"{U}/code/experiments/2026-10-test-skill"
HEAD = ("You are working in a checkout of shopizer, a Java e-commerce platform "
        "(Maven, several modules; JDK 21 is installed and JAVA_HOME is set).\n\n")
TAIL = "\n\nWhen you have finished, reply with one short paragraph saying what you changed."
PATH = f"/opt/homebrew/opt/openjdk@21/bin:{U}/.local/bin:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
W = f"{U}/code/benchmark/skills-impact-work"


def arm(name, overlay=None, uses=None, prefix=None):
    s = f'[[arms]]\nname = "{name}"\n'
    if overlay:
        s += f'overlay = "{overlay}"\n'
    if prefix:
        assert "\"\"\"" not in prefix
        s += f'prompt_prefix = """{prefix}"""\n'
    s += f'setup = ["bash {X}/scripts/setup.sh"]\nparallel_setup = true\n'
    if uses:
        s += f'uses = "{uses}"\n'
    return s + "\n"


def agent(effort, home=f"{W}/home-clean", isolate=(f"{U}/code/experiments",), extra=()):
    iso = ", ".join(f'"{d}"' for d in list(isolate) + [f"{U}/.agents", f"{U}/.claude", f"{U}/.cursor", f"{U}/.codex"])
    return ('[[agents]]\nname = "codex"\nmodel = "gpt-5.6-luna"\nargs = [' + "".join(f'"{a}", ' for a in extra) + '"-c", "model_reasoning_effort=\\"' + effort + '\\""]\n'
            'edits = true\nsandbox = "danger-full-access"\n'
            f'env = {{ HOME = "{home}", CODEX_HOME = "{home}/.codex", JAVA_HOME = "/opt/homebrew/opt/openjdk@21", PATH = "{PATH}" }}\n'
            f'isolate = [{iso}]\n\n')


def head(name, reps, timeout, baseline, claim):
    return (f"# Absolute paths are written for {U}. Run scripts/localize.sh to write *.local.toml with your home folder.\n"
            f'# Generated by scripts/make_trial.py.\nname = "{name}"\n\n'
            f"[defaults]\nreps = {reps}\nparallel = 3\ntimeout = {timeout}\nbaseline = \"{baseline}\"\nclaim = {claim}\n\n"
            f'[[repos]]\nname = "shopizer"\nsource = "{W}/shopizer"\nref = "6a4a0a6"\n\n')


def question(qid, prompt, verify):
    assert '"""' not in prompt
    return f'[[questions]]\nid = "{qid}"\nrepo = "shopizer"\nverify = "{verify}"\nprompt = """{prompt}"""\n\n'


if __name__ == "__main__":
    tasks = sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(E, "tasks", "*", "prompt.md")))
    skills = "\\\\.agents/skills/[^ ]*SKILL\\\\.md"
    instr = open(os.path.join(E, "arms", "instruction.md")).read().strip()
    instr_skill = open(os.path.join(E, "arms", "instruction-skill.md")).read().strip()
    qs = "".join(question(t, HEAD + open(os.path.join(E, "tasks", t, "prompt.md")).read().strip() + TAIL,
                          f"bash {X}/scripts/verify.sh") for t in tasks)
    open(os.path.join(E, "trial.toml"), "w").write(
        head("test-skill", 3, 1800, "none", "true") + arm("none") + arm("instruction", prefix=instr)
        + arm("skill", "arms/skill-original", skills, instr_skill) + arm("skill-revised", "arms/skill-revised", skills, instr_skill)
        + agent("low") + qs)
    open(os.path.join(E, "trial-medium.toml"), "w").write(
        head("test-skill-medium", 3, 1800, "medium", "true") + arm("medium") + agent("medium") + qs)
    open(os.path.join(E, "trial-gate.toml"), "w").write(
        head("test-skill-gate", 3, 2700, "gate", "true") + arm("gate")
        + agent("low", home=f"{W}/home-gate", extra=("--dangerously-bypass-hook-trust",)) + qs)
    print(f"trial.toml, trial-medium.toml and trial-gate.toml with {len(tasks)} tasks")
