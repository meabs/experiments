"""Writes split-spec's trial files (Linux, bubblewrap via local-setup/codex-bwrap.sh, hosted gpt-5.6-luna at medium effort).
See README.md for the design. Built from swarm-tax's make_trial.py.

One trial file per arm, because the installed AgentTrialRig (0.7.0) has no per-arm prompt option: an arm's instruction
(arms/*.md) is written into each task prompt here, and the team files add --enable multi_agent_v2. The team arms' setup
(scripts/setup-spec.sh) also puts the task in the clone as TASK.md. Prompts: HEAD + [instruction +] task + TAIL.

- trial-<arm>.local.toml for solo, team-spec, split-part and split-full: every task in tasks/.
- trial-smoke-<arm>.local.toml: 1 run of the arm on the tasks given with --smoke.

Usage: python3 -I make_trial.py [--smoke TASK[,TASK]]
"""
import glob, os, sys, tomllib

E = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
U = os.path.expanduser("~")
X = f"{U}/code/experiments/2026-10-split-spec"
S = f"{U}/code/benchmark/local-setup"
JDK = "/usr/lib/jvm/java-21-openjdk-amd64"
HEAD = ("You are working in a checkout of shopizer, a Java e-commerce platform "
        "(Maven, several modules; JDK 21 is installed and JAVA_HOME is set).\n\n")
TAIL = "\n\nWhen you have finished, reply with one short paragraph saying what you changed."
EFFORT = "medium"
REPS = {"solo": 6, "team-spec": 6, "split-part": 6, "split-full": 6}
TIMEOUT = {"solo": 2700, "team-spec": 3600, "split-part": 3600, "split-full": 3600}
ARMS = {"solo": None, "team-spec": "team-spec.md", "split-part": "split-part.md", "split-full": "split-full.md"}
SETUP = {a: "setup-spec.sh" for a in ARMS if a != "solo"}


def agent(multi):
    cmd = ["bash", f"{S}/codex-bwrap.sh", "exec", "-s", "danger-full-access", "--skip-git-repo-check", "--json"]
    cmd += ["--enable", "multi_agent_v2"] if multi else []
    cmd += ["--model", "gpt-5.6-luna", "-c", f'model_reasoning_effort="{EFFORT}"', "{prompt}"]
    return ('[[agents]]\nname = "codex"\n'
            '# hosted gpt-5.6-luna (CODEX_PROFILE=hosted); codex runs inside bubblewrap (codex-bwrap.sh) since `isolate` is macOS-only\n'
            'model = "gpt-5.6-luna"\ncommand = [' + ", ".join('"' + c.replace('"', '\\"') + '"' for c in cmd) + ']\n'
            'args = []\nedits = true\nsandbox = "danger-full-access"\n'
            f'env = {{ JAVA_HOME = "{JDK}", PATH = "{JDK}/bin:/usr/local/bin:/usr/bin:/bin", CODEX_PROFILE = "hosted" }}\n'
            'isolate = []\n\n')


def trial(name, arm, tasks, reps):
    texts = ARMS
    instr = open(os.path.join(E, "arms", texts[arm])).read().strip() + "\n\n" if texts[arm] else ""
    s = (f"# Generated by 2026-10-split-spec/scripts/make_trial.py. Arm {arm}, effort {EFFORT}.\n"
         f'name = "{name}"\n\n[defaults]\nreps = {reps}\nparallel = 2\ntimeout = {TIMEOUT[arm]}\nbaseline = "{arm}"\nclaim = true\n\n'
         f'[[repos]]\nname = "shopizer"\nsource = "{U}/code/benchmark/skills-impact-work/shopizer"\nref = "6a4a0a6"\n\n'
         f'[[arms]]\nname = "{arm}"\nsetup = ["bash {X}/scripts/{SETUP.get(arm, 'setup.sh')}"]\nparallel_setup = true\n\n' + agent(arm != "solo"))
    for t in tasks:
        p = HEAD + instr + open(os.path.join(E, "tasks", t, "prompt.md")).read().strip() + TAIL
        assert '"""' not in p
        s += f'[[questions]]\nid = "{t}"\nrepo = "shopizer"\nverify = "bash {X}/scripts/verify.sh"\nprompt = """{p}"""\n\n'
    return s


if __name__ == "__main__":
    tasks = sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(E, "tasks", "*", "prompt.md")))
    out = {f"trial-{a}.local.toml": trial(f"split-spec-{a}", a, tasks, REPS[a]) for a in ARMS}
    if "--smoke" in sys.argv:
        smoke = sys.argv[sys.argv.index("--smoke") + 1].split(",")
        out = {f"trial-smoke-{a}.local.toml": trial(f"split-spec-smoke-{a}", a, smoke, 1) for a in ARMS}
    for f, text in out.items():
        t = tomllib.loads(text)
        a = t["agents"][0]
        arm = t["arms"][0]["name"]
        assert ("multi_agent_v2" in a["command"]) == (arm != "solo") and f'model_reasoning_effort="{EFFORT}"' in a["command"]
        assert all(("You are the planner." in q["prompt"]) == (arm != "solo") for q in t["questions"])
        assert all(("TASK.md" in q["prompt"]) == (arm != "solo") for q in t["questions"])
        assert all((".team/part-N.md" in q["prompt"]) == arm.startswith("split") for q in t["questions"])
        open(os.path.join(E, f), "w").write(text)
        print(f, arm, len(t["questions"]), "tasks, reps", t["defaults"]["reps"], "timeout", t["defaults"]["timeout"])
