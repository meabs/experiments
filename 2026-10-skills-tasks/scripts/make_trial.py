"""Writes trial.toml (measured runs) and calibration.toml (control only) from tasks/*/prompt.md.

Usage: python3 -I make_trial.py [TASK ...]. With task ids, trial.toml includes only those (the selected tasks);
calibration.toml always includes every task. Paths use the /Users/USER placeholder; run scripts/localize.sh after.
"""
import glob, os, sys

E = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
U = "/Users/USER"
X = f"{U}/code/experiments/2026-10-skills-tasks"
HEAD = ("You are working in a checkout of shopizer, a Java e-commerce platform "
        "(Maven, several modules; JDK 21 is installed and JAVA_HOME is set).\n\n")
TAIL = "\n\nWhen you have finished, reply with one short paragraph saying what you changed."
EFFORT = "low"  # user decision 2026-10-21: high effort was at the ceiling (see README amendment log)
# CUSTPAGE and CUSTSEARCH are folded into HCUST, so they are not in the pool.
EXCLUDE = {"CUSTPAGE", "CUSTSEARCH"}
PATH = f"/opt/homebrew/opt/openjdk@21/bin:{U}/.local/bin:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"


def arm(name, overlay=None, uses=None):
    s = f'[[arms]]\nname = "{name}"\n'
    if overlay:
        s += f'overlay = "{overlay}"\n'
    s += f'setup = ["bash {X}/scripts/setup.sh"]\nparallel_setup = true\n'
    if uses:
        s += f'uses = "{uses}"\n'
    return s + "\n"


def agent():
    w = f"{U}/code/benchmark/skills-impact-work"
    return ('[[agents]]\nname = "codex"\nmodel = "gpt-5.6-luna"\nargs = ["-c", "model_reasoning_effort=\\"' + EFFORT + '\\""]\n'
            'edits = true\nsandbox = "danger-full-access"\n'
            f'env = {{ HOME = "{w}/home-clean", CODEX_HOME = "{w}/home-clean/.codex", JAVA_HOME = "/opt/homebrew/opt/openjdk@21", PATH = "{PATH}" }}\n'
            f'isolate = ["{U}/code/experiments", "{U}/.agents", "{U}/.claude", "{U}/.cursor", "{U}/.codex"]\n\n')


def questions(ids):
    out = ""
    for t in ids:
        p = open(os.path.join(E, "tasks", t, "prompt.md")).read().strip()
        assert '"""' not in p
        out += (f'[[questions]]\nid = "{t}"\nrepo = "shopizer"\nverify = "bash {X}/scripts/verify.sh"\n'
                f'prompt = """{HEAD}{p}{TAIL}"""\n\n')
    return out


def write(path, name, reps, arms, ids):
    head = (f"# Absolute paths are written for {U}. Run scripts/localize.sh to write *.local.toml with your home folder.\n"
            f'# Generated by scripts/make_trial.py; edit the task prompts, not this file.\nname = "{name}"\n\n'
            f"[defaults]\nreps = {reps}\nparallel = 3\ntimeout = 1200\nbaseline = \"none\"\nclaim = true\n\n"
            f'[[repos]]\nname = "shopizer"\nsource = "{U}/code/benchmark/skills-impact-work/shopizer"\nref = "6a4a0a6"\n\n')
    open(path, "w").write(head + "".join(arms) + agent() + questions(ids))


if __name__ == "__main__":
    every = sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(E, "tasks", "*", "prompt.md"))
                   if os.path.basename(os.path.dirname(p)) not in EXCLUDE)
    chosen = sys.argv[1:] or every
    skills = "\\\\.agents/skills/[^ ]*SKILL\\\\.md"
    write(os.path.join(E, "calibration.toml"), "skills-tasks-calibration", 2, [arm("none")], every)
    write(os.path.join(E, "trial.toml"), "skills-tasks", 2,
          [arm("none"), arm("placebo", "arms/placebo", "careful-engineering"), arm("superpowers", "arms/superpowers", skills),
           arm("pocock", "arms/pocock", skills)], chosen)
    print(f"calibration: {len(every)} tasks; trial: {len(chosen)} tasks")
