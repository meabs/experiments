"""Writes the trial files: trial-<arm>.local.toml (6 briefs, REPS runs each) and trial-pilot-<arm>.local.toml (1 run).
Agent: Codex CLI, hosted gpt-5.6-luna, medium effort, web search live, inside bubblewrap (local-setup/codex-bwrap.sh).
The prompt is identical in both arms: a fixed header, the brief, and the delivery contract. The arms differ only in
the files scripts/setup.sh lays down (arm B gets the Design Factory; Codex loads its AGENTS.md by itself).
Usage: python3 -I make_trial.py
"""
import os, tomllib

E = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
U = os.path.expanduser("~")
S = f"{U}/code/benchmark/local-setup"
W = os.environ.get("DF_WORK", f"{U}/code/benchmark/df-work")
JDK = "/usr/lib/jvm/java-21-openjdk-amd64"
EFFORT = "medium"
ARMS = {"C": "plain plus one line", "D": "Design Factory v2"}
EXTRA = {"C": "\n\nBe ambitious and distinctive: aim for a design people would remember."}
BRIEFS = ["F1"]
REPS = 5
TIMEOUT = 2700
HEAD = ("You are a designer on the design and front-end team at Brindle Bank, a fictional UK retail bank, working on "
        "its mobile banking app.\n\n")
CONTRACT = """

Your task:

1. Research, using web search: who the next generation of banking customers are, what they expect and will need, and
   which trends and ideas are shaping the future of mobile banking and fintech (needs, features, visual style,
   interaction, content). Write what you found, with sources, in `research.md`.
2. From that research, your own knowledge and any skills or guidance available in this workspace, choose the features
   of your futuristic app. List them in `research.md` as numbered features (F1, F2, ...): what each is, which research
   finding supports it, and which storyboard frame shows it.
3. Create a storyboard of the app: 8 to 12 frames showing the chosen features and the key moments of using the app,
   in the order a user meets them.

Deliver the storyboard in `storyboard/index.html`: HTML and CSS (JavaScript only if you want it) that runs offline by
opening the file. Each frame is a phone screen exactly 390 px wide and 844 px tall; frames must not shrink, overlap or
need a device mock-up to be understood, and must display correctly in a desktop browser 1280 px wide. Every frame must
also open directly at `storyboard/index.html#<frame-id>`. List the frames in order in `storyboard/screens.json`:
`[{"id": "<frame-id>", "title": "..."}]`.

Nobody is available to answer questions. Make reasonable assumptions and finish the work."""


def agent():
    cmd = ["bash", f"{S}/codex-bwrap.sh", "exec", "-s", "danger-full-access", "--skip-git-repo-check", "--json",
           "--model", "gpt-5.6-luna", "-c", f'model_reasoning_effort="{EFFORT}"', "-c", 'web_search="live"',
           "{prompt}"]
    return ('[[agents]]\nname = "codex"\n'
            '# hosted gpt-5.6-luna (CODEX_PROFILE=hosted); codex runs inside bubblewrap (codex-bwrap.sh)\n'
            'model = "gpt-5.6-luna"\ncommand = [' + ", ".join('"' + c.replace('"', '\\"') + '"' for c in cmd) + ']\n'
            'args = []\nedits = true\nsandbox = "danger-full-access"\n'
            f'env = {{ JAVA_HOME = "{JDK}", PATH = "{JDK}/bin:/usr/local/bin:/usr/bin:/bin", CODEX_PROFILE = "hosted" }}\n'
            'isolate = []\n\n')


def trial(name, arm, reps):
    s = (f"# Generated by 2026-11-design-factory/scripts/make_trial.py. Arm {arm} ({ARMS[arm]}), effort {EFFORT}.\n"
         f'name = "{name}"\n\n[defaults]\nreps = {reps}\nparallel = 3\ntimeout = {TIMEOUT}\nbaseline = "{arm}"\n'
         f'claim = false\n\n[[repos]]\nname = "workspace"\nsource = "{W}/base"\n\n'
         f'[[arms]]\nname = "{arm}"\nsetup = ["bash {E}/scripts/setup.sh {arm}"]\nparallel_setup = true\n')
    if arm == "D":
        s += "uses = 'okf/'\n"
    s += "\n" + agent()
    for b in BRIEFS:
        p = HEAD + open(os.path.join(E, "briefs", b, "prompt.md")).read().strip() + EXTRA.get(arm, "") + CONTRACT
        assert '"""' not in p
        s += f'[[questions]]\nid = "{b}"\nrepo = "workspace"\nverify = "bash {E}/scripts/verify.sh"\nprompt = """{p}"""\n\n'
    return s


if __name__ == "__main__":
    for a in ARMS:
        for pre, reps in (("trial", REPS), ("trial-pilot", 1)):
            text = trial(f"factory-v2-{'pilot-' if 'pilot' in pre else ''}{a}", a, reps)
            t = tomllib.loads(text)
            ag = t["agents"][0]
            assert f'model_reasoning_effort="{EFFORT}"' in ag["command"] and ag["env"]["CODEX_PROFILE"] == "hosted"
            assert 'web_search="live"' in ag["command"]
            f = f"{pre}-{a}.local.toml"
            open(os.path.join(E, f), "w").write(text)
            print(f, len(t["questions"]), "briefs, reps", t["defaults"]["reps"])
