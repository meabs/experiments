"""Writes webmcp-resilience's trial files (Linux, bubblewrap via local-setup/codex-bwrap.sh, hosted gpt-5.6-luna at
medium effort). See README.md for the design. Built from split-spec's make_trial.py.
One trial file per arm: the arm decides the setup (scripts/setup.sh <arm>) and the Python environment bound into the
sandbox (CODEX_RO_BIND: the arm's environment and Playwright's browser cache, both read-only).
- trial-<arm>.local.toml for plain, tool and tool-recipes: every task in tasks/.
- trial-smoke-<arm>.local.toml: 1 run of the arm on the tasks given with --smoke.
- --local: the local qwen3.8:27b (or $WEBMCP_LOCAL_MODEL) through Ollama (local-setup's default Codex profile, web search off) instead of
  hosted gpt-5.6-luna; files are named trial-local-*.
Usage: python3 -I make_trial.py [--local] [--smoke TASK[,TASK]]
"""
import glob, os, sys, tomllib

E = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
U = os.path.expanduser("~")
S = f"{U}/code/benchmark/local-setup"
X = f"{U}/code/benchmark/webmcp-exp"
HEAD = "You are working on a web page in this folder (see README.md and AGENTS.md).\n\n"
TAIL = "\n\nWhen you have finished, reply with one short paragraph saying what you changed and how you checked it."
EFFORT = "medium"
REPS = 6
TIMEOUT = 1800
ARMS = ["plain", "tool", "tool-recipes"]
ENV = {"plain": "env-plain", "tool": "env-tool", "tool-recipes": "env-tool"}


LOCAL = "--local" in sys.argv
MODEL = os.environ.get("WEBMCP_LOCAL_MODEL", "qwen3.8:27b") if LOCAL else "gpt-5.6-luna"


def agent(arm):
    cmd = ["bash", f"{S}/codex-bwrap.sh", "exec", "-s", "danger-full-access", "--skip-git-repo-check", "--json",
           "--model", MODEL, "-c", f'model_reasoning_effort="{EFFORT}"']
    if LOCAL:
        cmd += ["-c", 'web_search="disabled"']  # Ollama's web search needs an account (okf-local amendment)
    cmd += ["{prompt}"]
    ro = f"{X}/{ENV[arm]}:{U}/.cache/ms-playwright"
    profile = "" if LOCAL else 'CODEX_PROFILE = "hosted", '
    note = ("local qwen3.8:27b through Ollama (default profile)" if LOCAL else "hosted gpt-5.6-luna (CODEX_PROFILE=hosted)")
    return ('[[agents]]\nname = "codex"\n'
            f'# {note}; codex runs inside bubblewrap (codex-bwrap.sh)\n'
            f'model = "{MODEL}"\ncommand = [' + ", ".join('"' + c.replace('"', '\\"') + '"' for c in cmd) + ']\n'
            'args = []\nedits = true\nsandbox = "danger-full-access"\n'
            f'env = {{ PATH = "/usr/local/bin:/usr/bin:/bin", {profile}CODEX_RO_BIND = "{ro}" }}\n'
            'isolate = []\n\n')


def trial(name, arm, tasks, reps):
    s = (f"# Generated by 2026-10-webmcp-resilience/scripts/make_trial.py. Arm {arm}, model {MODEL}, effort {EFFORT}.\n"
         f'name = "{name}"\n\n[defaults]\nreps = {reps}\nparallel = {1 if LOCAL else 3}\ntimeout = {TIMEOUT}\nbaseline = "{arm}"\nclaim = true\n\n')
    for t in tasks:
        s += f'[[repos]]\nname = "{t}"\nsource = "{X}/repos/{t}"\n\n'
    s += (f'[[arms]]\nname = "{arm}"\nsetup = ["bash {E}/scripts/setup.sh {arm}"]\nparallel_setup = true\n\n' + agent(arm))
    for t in tasks:
        p = HEAD + open(os.path.join(E, "tasks", t, "prompt.md")).read().strip() + TAIL
        assert '"""' not in p
        s += f'[[questions]]\nid = "{t}"\nrepo = "{t}"\nverify = "bash {E}/scripts/verify.sh"\nprompt = """{p}"""\n\n'
    return s


if __name__ == "__main__":
    tasks = sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(E, "tasks", "*", "prompt.md")))
    pre = "local-" if LOCAL else ""
    out = {f"trial-{pre}{a}.local.toml": trial(f"webmcp-resilience-{pre}{a}", a, tasks, REPS) for a in ARMS}
    if "--smoke" in sys.argv:
        smoke = sys.argv[sys.argv.index("--smoke") + 1].split(",")
        out = {f"trial-{pre}smoke-{a}.local.toml": trial(f"webmcp-resilience-{pre}smoke-{a}", a, smoke, 1) for a in ARMS}
    for f, text in out.items():
        t = tomllib.loads(text)
        a = t["agents"][0]
        arm = t["arms"][0]["name"]
        assert f'model_reasoning_effort="{EFFORT}"' in a["command"] and MODEL in a["command"]
        assert ("CODEX_PROFILE" not in a["env"]) if LOCAL else (a["env"]["CODEX_PROFILE"] == "hosted")
        assert ENV[arm] in a["env"]["CODEX_RO_BIND"] and t["arms"][0]["setup"][0].endswith(f"setup.sh {arm}")
        open(os.path.join(E, f), "w").write(text)
        print(f, arm, len(t["questions"]), "tasks, reps", t["defaults"]["reps"], "timeout", t["defaults"]["timeout"])
