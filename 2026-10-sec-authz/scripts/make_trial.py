"""Writes sec-authz's trial files (Linux, bubblewrap via local-setup/codex-bwrap.sh, hosted gpt-5.6-luna at medium
effort). See README.md for the design. One trial file per arm, so scripts/run_all.sh can rotate the arms within each
repetition:
- trial-<arm>.local.toml for A, B, C, D: the 8 tasks.
- --pilot: trial-pilot-<arm>.local.toml, 1 run each: arm A on all 8 tasks, arms B, C and D on PILOT_TASKS.
Usage: python3 -I make_trial.py [--pilot]
"""
import os, sys, tomllib

E = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
U = os.path.expanduser("~")
S = f"{U}/code/benchmark/local-setup"
W = os.environ.get("SEC_WORK", f"{U}/code/benchmark/sec-authz-work")
JDK = "/usr/lib/jvm/java-21-openjdk-amd64"
EFFORT = "medium"
REPS = 10
TIMEOUT = 900
ARMS = ["A", "B", "C", "D"]
TASKS = [f"S0{i}" for i in range(1, 9)]
PILOT_TASKS = ["S01", "S05", "S08"]
USES = {"B": r"spring-api-authorisation/SKILL\.md", "C": r"verify-authz", "D": r"spring-api-authorisation/SKILL\.md"}
HEAD = "You are working on accounts-service, the Spring Boot API in this repository (see README.md and AGENTS.md).\n\n"


def agent():
    cmd = ["bash", f"{S}/codex-bwrap.sh", "exec", "-s", "danger-full-access", "--skip-git-repo-check", "--json",
           "--model", "gpt-5.6-luna", "-c", f'model_reasoning_effort="{EFFORT}"', "{prompt}"]
    return ('[[agents]]\nname = "codex"\n'
            '# hosted gpt-5.6-luna (CODEX_PROFILE=hosted); codex runs inside bubblewrap (codex-bwrap.sh)\n'
            'model = "gpt-5.6-luna"\ncommand = [' + ", ".join('"' + c.replace('"', '\\"') + '"' for c in cmd) + ']\n'
            'args = []\nedits = true\nsandbox = "danger-full-access"\n'
            f'env = {{ JAVA_HOME = "{JDK}", PATH = "{JDK}/bin:/usr/local/bin:/usr/bin:/bin", CODEX_PROFILE = "hosted" }}\n'
            'isolate = []\n\n')


def trial(name, arm, tasks, reps):
    s = (f"# Generated by 2026-10-sec-authz/scripts/make_trial.py. Arm {arm}, effort {EFFORT}.\n"
         f'name = "{name}"\n\n[defaults]\nreps = {reps}\nparallel = 3\ntimeout = {TIMEOUT}\nbaseline = "{arm}"\nclaim = true\n\n'
         f'[[repos]]\nname = "accounts-service"\nsource = "{W}/accounts-service"\n\n'
         f'[[arms]]\nname = "{arm}"\nsetup = ["bash {E}/scripts/setup.sh {arm}"]\nparallel_setup = true\n')
    if arm in USES:
        s += f"uses = '{USES[arm]}'\n"
    s += "\n" + agent()
    for t in tasks:
        p = HEAD + open(os.path.join(E, "tasks", t, "prompt.md")).read().strip()
        assert '"""' not in p
        s += f'[[questions]]\nid = "{t}"\nrepo = "accounts-service"\nverify = "bash {E}/scripts/verify.sh"\nprompt = """{p}"""\n\n'
    return s


if __name__ == "__main__":
    if "--pilot" in sys.argv:
        out = {f"trial-pilot-{a}.local.toml": trial(f"sec-authz-pilot-{a}", a, TASKS if a == "A" else PILOT_TASKS, 1)
               for a in ARMS}
    else:
        out = {f"trial-{a}.local.toml": trial(f"sec-authz-{a}", a, TASKS, REPS) for a in ARMS}
    for f, text in out.items():
        t = tomllib.loads(text)
        a = t["agents"][0]
        assert f'model_reasoning_effort="{EFFORT}"' in a["command"] and a["env"]["CODEX_PROFILE"] == "hosted"
        open(os.path.join(E, f), "w").write(text)
        print(f, t["arms"][0]["name"], len(t["questions"]), "tasks, reps", t["defaults"]["reps"], "uses", t["arms"][0].get("uses"))
